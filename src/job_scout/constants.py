def title_relevant(title: str) -> bool:
    """标题是否与 AI/Agent 开发相关：先排非技术岗，再看关键词。"""
    low = (title or "").lower()
    if any(k in low for k in NON_TECH_KEYWORDS):
        return False
    return any(k in low for k in RELEVANT_KEYWORDS)
